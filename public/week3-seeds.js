async function seed(){
  try{
    const r=await fetch('/api/builder/sessions',{cache:'no-store'});if(!r.ok)return;
    const data=await r.json(),ids=new Set((data.sessions||[]).map(x=>x.id));let added=0;
    for(const session of sessions){
      if(ids.has(session.id))continue;
      const res=await fetch('/api/builder/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(session)});
      if(res.ok)added++;
    }
    if(added){sessionStorage.setItem('showrunner-week3-seeded','1');location.reload();}
  }catch(e){console.warn('Week 3 seed skipped',e)}
}
if(location.pathname==='/builder')seed();
